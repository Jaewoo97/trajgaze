"""
HD-EPIC dataset for TrajGazeMerge — same per-item contract as
StreamGazeMergeDataset / EgoGazeVQADataset, so it can be concatenated.

Sources:
  videos             : /workspace/HD-EPIC/video/P##/{stem}.mp4   (not loaded here)
  pre-extracted JPEG : /workspace/HD-EPIC/frames_extracted/P##/{stem}/frame_NNNNNN.jpg
                       (10 fps, 224×224 — see /workspace/extract_hdepic_frames.sh)
  hand               : /workspace/HD-EPIC/hand_locations/{stem}.json  (StreamGaze-schema
                       — mask centroids in 224-px coords, see tools/parse_hdepic_hands.py)
  gaze               : absent  (HD-EPIC eye-gaze is in Aria MPS CPF radians;
                                projecting requires the Aria SDK — out of scope for the
                                user-requested "parse hand coords" step. The trajectory
                                pipeline gracefully degrades when gaze is None.)
  interaction        : /workspace/HD-EPIC/interaction/{stem}.npz  (generated by
                       tools/make_hdepic_interaction.py — StreamGaze schema)

VQA:
  /workspace/hd-epic-annotations/vqa-benchmark/*.json
  30 task JSON files. Each item:
    "<task>_<n>": {
        "inputs": {"video 1": {"id": "<stem>"}, "video 2": {...}, ...},
        "question": str  (may contain "<TIME mm:ss.ms videoN>" / "<BBOX x1 y1 x2 y2>")
        "choices":  [str × 5],
        "correct_idx": int (0..4)
    }

Split: items whose primary video belongs to participant P09 → val ('test');
       everything else → train.  Multi-video items: union of participants;
       if any cited video belongs to P09 → val (keeps split clean).
"""
from __future__ import annotations

import glob
import json
import os
import re
from typing import Optional

import numpy as np
import torch
from torch.utils.data import Dataset

ROOT          = "/workspace/HD-EPIC"
# GAZE_OVERLAY=1 (default) → frames_gaze mirror with the gaze marker drawn in
# pixels (matches StreamGaze viz + EgoGazeVQA gaze); =0 → raw frames_extracted.
FRAMES_BASE   = os.path.join(
    ROOT, "frames_gaze" if os.environ.get("GAZE_OVERLAY", "1") == "1"
    else "frames_extracted")
HAND_BASE     = os.path.join(ROOT, "hand_locations")
GAZE_BASE     = os.path.join(ROOT, "gaze")
INTER_BASE    = os.path.join(ROOT, "interaction")
VQA_BASE      = "/workspace/hd-epic-annotations/vqa-benchmark"
VAL_SPLIT_OUT = os.path.join(ROOT, "val_items.json")

VAL_PARTICIPANT = "P09"
EXTRACT_FPS = 10.0
WINDOW_SEC  = 10.0   # frames sampled in [t - W, t + W] for each <TIME> tag

TIME_RE = re.compile(r"<TIME\s+([\d:.]+)\s+video\s*(\d+)\s*>", re.IGNORECASE)


def _participant_of(video_id: str) -> str:
    return video_id.split("-", 1)[0]   # "P01-20240202-110250" → "P01"


def _parse_time(s: str) -> float:
    # "00:03:1.8" or "01:23.4" → seconds
    parts = s.split(":")
    parts = [float(p) for p in parts]
    if len(parts) == 1:
        return parts[0]
    if len(parts) == 2:
        return parts[0] * 60 + parts[1]
    if len(parts) == 3:
        return parts[0] * 3600 + parts[1] * 60 + parts[2]
    return 0.0


def _frame_dir(stem: str) -> str:
    return os.path.join(FRAMES_BASE, _participant_of(stem), stem)


def _all_frames(stem: str) -> list[str]:
    d = _frame_dir(stem)
    if not os.path.isdir(d):
        return []
    return sorted(os.path.join(d, f) for f in os.listdir(d) if f.endswith(".jpg"))


def _sample_paths(paths: list[str], n: int) -> list[str]:
    if not paths:
        return []
    if len(paths) <= n:
        return paths
    indices = [int(i * len(paths) / n) for i in range(n)]
    return [paths[i] for i in indices]


def _frames_for_inputs(inputs: dict, question: str, n_total: int) -> list[str]:
    """
    Given an item's `inputs` dict (video N → {id}) and the question text
    (which may contain <TIME mm:ss.ms videoN> tags), produce a list of frame
    paths sampled around the cited time windows; falls back to whole-video
    uniform sampling when no TIME tag references a given video.

    For multi-video items, frames from each cited video are concatenated.
    """
    # collect TIME tags per video index
    tags_by_video: dict[str, list[float]] = {}
    for m in TIME_RE.finditer(question or ""):
        t = _parse_time(m.group(1))
        v = f"video {int(m.group(2))}"
        tags_by_video.setdefault(v, []).append(t)

    # gather video stems in order video1, video2, ...
    keys = sorted(inputs.keys(), key=lambda k: int(re.findall(r"\d+", k)[0]) if re.findall(r"\d+", k) else 0)
    per_video_paths: list[list[str]] = []
    for vk in keys:
        stem = inputs[vk].get("id") if isinstance(inputs[vk], dict) else None
        if not stem:
            continue
        allf = _all_frames(stem)
        if not allf:
            continue
        ts = tags_by_video.get(vk)
        if ts:
            mask = np.zeros(len(allf), dtype=bool)
            for t in ts:
                f_idx = int(round(t * EXTRACT_FPS))
                lo = max(0, f_idx - int(WINDOW_SEC * EXTRACT_FPS))
                hi = min(len(allf), f_idx + int(WINDOW_SEC * EXTRACT_FPS))
                mask[lo:hi] = True
            sel = [allf[i] for i in range(len(allf)) if mask[i]]
            if not sel:
                sel = allf
        else:
            sel = allf
        per_video_paths.append(sel)

    if not per_video_paths:
        return []
    # distribute n_total roughly evenly across videos, preserving order
    nv = len(per_video_paths)
    quotas = [n_total // nv] * nv
    for i in range(n_total - sum(quotas)):
        quotas[i] += 1
    out: list[str] = []
    for paths, q in zip(per_video_paths, quotas):
        out.extend(_sample_paths(paths, max(1, q)))
    return out


def _load_traj_hdepic(stem: str, frame_paths: list[str],
                       n_traj_frames: int) -> tuple[dict, list[str]]:
    """Mirror StreamGaze _load_traj for HD-EPIC. Gaze is read from
    /workspace/HD-EPIC/gaze/{stem}.json (Aria MPS CPF→camera-rgb pixel
    projection, see scripts/project_hdepic_gaze.py). Values are
    normalized [0,1]; missing recordings → gaze-absent (hand-only)."""
    sampled = _sample_paths(frame_paths, n_traj_frames)
    T = len(sampled)
    if T == 0:
        return {}, []

    hand_path = os.path.join(HAND_BASE, f"{stem}.json")
    hand_json: dict = {}
    if os.path.exists(hand_path):
        try:
            hand_json = json.load(open(hand_path))
        except Exception:
            hand_json = {}

    gaze_path = os.path.join(GAZE_BASE, f"{stem}.json")
    gaze_json: dict = {}
    if os.path.exists(gaze_path):
        try:
            gaze_json = json.load(open(gaze_path))
        except Exception:
            gaze_json = {}

    npz_path = os.path.join(INTER_BASE, f"{stem}.npz")
    npz = np.load(npz_path) if os.path.exists(npz_path) else None
    int_idx: dict[str, int] = {}
    if npz is not None:
        for i, fn in enumerate(npz["frame_names"]):
            int_idx[str(fn)] = int(i)

    # extracted frames are 224×224 by construction (see extract_hdepic_frames.sh)
    img_w, img_h = 224, 224

    gaze_pos   = np.zeros((T, 2), np.float32)
    gaze_speed = np.zeros((T, 1), np.float32)
    gaze_mask  = np.zeros(T, bool)
    left_pos   = np.zeros((T, 2), np.float32)
    left_vel   = np.zeros((T, 2), np.float32)
    left_mask  = np.zeros(T, bool)
    right_pos  = np.zeros((T, 2), np.float32)
    right_vel  = np.zeros((T, 2), np.float32)
    right_mask = np.zeros(T, bool)
    d_left      = np.zeros((T, 3), np.float32)
    d_right     = np.zeros((T, 3), np.float32)
    v_rel_left  = np.zeros((T, 2), np.float32)
    v_rel_right = np.zeros((T, 2), np.float32)
    convergence = np.zeros(T, np.float32)
    lead_lag    = np.zeros(T, np.float32)

    for t, fpath in enumerate(sampled):
        fname = os.path.basename(fpath)
        h = hand_json.get(fname)
        if isinstance(h, dict):
            lh = h.get("left")
            if lh and lh[0] is not None:
                left_pos[t, 0] = float(lh[0]) / img_w
                left_pos[t, 1] = float(lh[1]) / img_h
                left_mask[t] = True
            rh = h.get("right")
            if rh and rh[0] is not None:
                right_pos[t, 0] = float(rh[0]) / img_w
                right_pos[t, 1] = float(rh[1]) / img_h
                right_mask[t] = True

        gv = gaze_json.get(fname)
        if gv and gv[0] is not None:
            gaze_pos[t, 0] = float(gv[0])
            gaze_pos[t, 1] = float(gv[1])
            gaze_mask[t] = True

        if npz is not None and fname in int_idx:
            ii = int_idx[fname]
            d_left[t]      = npz["d_left"][ii]
            d_right[t]     = npz["d_right"][ii]
            v_rel_left[t]  = npz["v_rel_left"][ii]
            v_rel_right[t] = npz["v_rel_right"][ii]
            convergence[t] = float(npz["convergence"][ii])
            lead_lag[t]    = float(npz["lead_lag"][ii])

    for t in range(1, T):
        if left_mask[t] and left_mask[t - 1]:
            left_vel[t] = left_pos[t] - left_pos[t - 1]
        if right_mask[t] and right_mask[t - 1]:
            right_vel[t] = right_pos[t] - right_pos[t - 1]
        if gaze_mask[t] and gaze_mask[t - 1]:
            gaze_speed[t, 0] = float(np.linalg.norm(gaze_pos[t] - gaze_pos[t - 1]))

    traj = {
        "gaze_pos":    torch.from_numpy(gaze_pos),
        "gaze_speed":  torch.from_numpy(gaze_speed),
        "gaze_mask":   torch.from_numpy(gaze_mask),
        "left_pos":    torch.from_numpy(left_pos),
        "left_vel":    torch.from_numpy(left_vel),
        "left_mask":   torch.from_numpy(left_mask),
        "right_pos":   torch.from_numpy(right_pos),
        "right_vel":   torch.from_numpy(right_vel),
        "right_mask":  torch.from_numpy(right_mask),
        "d_left":      torch.from_numpy(d_left),
        "d_right":     torch.from_numpy(d_right),
        "v_rel_left":  torch.from_numpy(v_rel_left),
        "v_rel_right": torch.from_numpy(v_rel_right),
        "convergence": torch.from_numpy(convergence),
        "lead_lag":    torch.from_numpy(lead_lag),
    }
    return traj, sampled


def _build_item_index(simple: bool, split: str,
                       n_vlm_frames: int, n_traj_frames: int) -> list[dict]:
    """Walk every vqa-benchmark JSON, filter by split, return item-meta list.
    Frames are not materialized here — that happens in __getitem__."""
    files = sorted(glob.glob(os.path.join(VQA_BASE, "*.json")))
    items: list[dict] = []
    val_ids: list[str] = []
    for f in files:
        task = os.path.splitext(os.path.basename(f))[0]
        try:
            data = json.load(open(f))
        except Exception:
            continue
        for qid, it in data.items():
            inputs = it.get("inputs", {})
            stems = []
            for vk in inputs:
                sid = inputs[vk].get("id") if isinstance(inputs[vk], dict) else None
                if sid:
                    stems.append(sid)
            if not stems:
                continue
            in_val = any(_participant_of(s) == VAL_PARTICIPANT for s in stems)
            if (split == "test") != in_val:
                continue
            choices = it.get("choices") or []
            cidx = it.get("correct_idx")
            if not choices or cidx is None or cidx < 0 or cidx >= len(choices):
                continue
            n_opt = len(choices)
            options = [f"{chr(65 + i)}. {c}" for i, c in enumerate(choices)]
            answer = chr(65 + int(cidx))
            items.append({
                "qid":      qid,
                "task":     task,
                "inputs":   inputs,        # dict video N -> {id}
                "stems":    stems,         # list[str] participant-prefixed
                "primary":  stems[0],
                "question": it.get("question", "") or "",
                "options":  options,
                "answer":   answer,
            })
            if in_val:
                val_ids.append(qid)
    # persist val item-id list once (only on first construction)
    if split == "test" and items and not os.path.exists(VAL_SPLIT_OUT):
        try:
            with open(VAL_SPLIT_OUT, "w") as f:
                json.dump({"val_participant": VAL_PARTICIPANT,
                            "n": len(val_ids), "qids": val_ids}, f)
        except Exception:
            pass
    return items


class HDEpicDataset(Dataset):
    """HD-EPIC VQA dataset, same per-item contract as the StreamGaze/EgoGazeVQA adapters."""

    def __init__(self,
                 split: str = "train",
                 n_vlm_frames: int = 128,
                 n_traj_frames: int = 32,
                 simple: bool = False):
        assert split in ("train", "test")
        self.split         = split
        self.n_vlm_frames  = n_vlm_frames
        self.n_traj_frames = n_traj_frames
        self.simple        = simple
        self.items         = _build_item_index(simple, split, n_vlm_frames, n_traj_frames)
        print(f"[HDEpicDataset] split={split} (val_participant={VAL_PARTICIPANT}) "
              f"simple={simple} → {len(self.items)} items "
              f"across {len(set(it['task'] for it in self.items))} tasks")

    def __len__(self) -> int:
        return len(self.items)

    def __getitem__(self, idx: int) -> Optional[dict]:
        it = self.items[idx]
        frame_paths = _frames_for_inputs(it["inputs"], it["question"], self.n_vlm_frames)
        if not frame_paths:
            return None
        if self.simple:
            return {
                "vlm_frame_paths": frame_paths,
                "question":        it["question"],
                "options":         it["options"],
                "answer":          it["answer"],
                "task":            it["task"],
                "dataset":         "hdepic",
            }
        # full path: also build traj (uses primary video's hand+interaction)
        try:
            traj, traj_frame_paths = _load_traj_hdepic(
                it["primary"], frame_paths, self.n_traj_frames,
            )
        except Exception:
            return None
        if not traj:
            return None
        return {
            "vlm_frame_paths":  frame_paths,
            "traj_frame_paths": traj_frame_paths,
            "traj":             traj,
            "question":         it["question"],
            "options":          it["options"],
            "answer":           it["answer"],
            "task":             it["task"],
            "dataset":          "hdepic",
        }
